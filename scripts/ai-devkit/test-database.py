"""Own disposable local PostgreSQL cluster only; never reads application .env."""
import argparse
import json
import os
from pathlib import Path
import secrets
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / '.cache/ai-devkit/postgres'
DATA = BASE / 'data'
PORT = 55439
DB = 'napare_devkit_test'
FLAGS = subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0

def run(args, **kwargs):
    # PostgreSQL descendants on Windows can inherit PIPE handles and keep
    # communicate() waiting after pg_ctl exits. File-backed output avoids that.
    with tempfile.TemporaryFile(mode='w+t', encoding='utf8') as output:
        result = subprocess.run([str(x) for x in args], stdout=output, stderr=output,
                                text=True, creationflags=FLAGS, timeout=90, **kwargs)
        output.seek(0)
        contents = output.read()
    if result.returncode:
        BASE.mkdir(parents=True, exist_ok=True)
        (BASE / 'last-operation.log').write_text(contents, encoding='utf8')
        raise RuntimeError('PostgreSQL operation failed (diagnostics retained locally): ' + str(args[0]))
    return contents

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['start', 'stop', 'status'])
    parser.add_argument('--pg-bin', type=Path)
    args = parser.parse_args()
    candidates = sorted(Path('C:/Program Files/PostgreSQL').glob('*/bin'), reverse=True) if os.name == 'nt' else []
    pg_bin = args.pg_bin or (Path(shutil.which('pg_ctl')).parent if shutil.which('pg_ctl') else next(iter(candidates), None))
    if not pg_bin or not (pg_bin / ('pg_ctl.exe' if os.name == 'nt' else 'pg_ctl')).exists():
        raise SystemExit('PostgreSQL binaries unavailable. Install PostgreSQL locally or pass --pg-bin. No application database was accessed.')
    ctl = pg_bin / 'pg_ctl'
    if args.action == 'stop':
        if DATA.exists(): run([ctl, '-D', DATA, '-m', 'fast', '-w', 'stop'])
        print('DevKit test cluster stopped; data preserved.')
        return
    if args.action == 'status':
        print(run([ctl, '-D', DATA, 'status']))
        return
    BASE.mkdir(parents=True, exist_ok=True)
    credentials = BASE / 'credentials.json'
    if not DATA.exists():
        admin = secrets.token_urlsafe(32)
        pwfile = BASE / 'init-password'
        pwfile.write_text(admin, encoding='utf8')
        try:
            run([pg_bin / 'initdb', '-D', DATA, '-U', 'devkit_admin', '--auth=scram-sha-256', '--pwfile', pwfile, '--encoding=UTF8', '--locale=C'])
        finally:
            pwfile.unlink(missing_ok=True)
        credentials.write_text(json.dumps({'admin': admin, 'reader': secrets.token_urlsafe(32)}), encoding='utf8')
    if not credentials.exists():
        raise SystemExit('Existing cluster lacks DevKit ownership credentials; refusing to alter it.')
    secret = json.loads(credentials.read_text(encoding='utf8'))
    status = subprocess.run([str(ctl), '-D', str(DATA), 'status'], capture_output=True, creationflags=FLAGS)
    if status.returncode:
        run([ctl, '-D', DATA, '-l', BASE / 'postgres.log', '-o', f'-h 127.0.0.1 -p {PORT}', '-w', 'start'])
    env = {**os.environ, 'PGPASSWORD': secret['admin']}
    psql = [pg_bin / 'psql', '-X', '-h', '127.0.0.1', '-p', PORT, '-U', 'devkit_admin', '-v', 'ON_ERROR_STOP=1']
    # Confirm ownership before creating a database, role or table.
    actual = run([*psql, '-d', 'postgres', '-Atc', 'SHOW data_directory'], env=env).strip()
    if Path(actual).resolve() != DATA.resolve():
        raise SystemExit('Unexpected server identity; refusing to configure DBHub.')
    # Names and passwords below are exclusively generated by this script.
    if run([*psql, '-d', 'postgres', '-Atc', f"SELECT 1 FROM pg_database WHERE datname='{DB}'"], env=env).strip() != '1':
        run([*psql, '-d', 'postgres', '-c', f'CREATE DATABASE {DB}'], env=env)
        sql = f"""CREATE ROLE devkit_reader LOGIN PASSWORD '{secret['reader']}';
REVOKE ALL ON DATABASE {DB} FROM PUBLIC;
GRANT CONNECT ON DATABASE {DB} TO devkit_reader;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
CREATE TABLE public.devkit_fixture (id integer PRIMARY KEY, label text NOT NULL);
INSERT INTO public.devkit_fixture VALUES (1, 'synthetic-only');
GRANT USAGE ON SCHEMA public TO devkit_reader;
GRANT SELECT ON public.devkit_fixture TO devkit_reader;
ALTER ROLE devkit_reader SET default_transaction_read_only = on;"""
        run([*psql, '-d', DB], input=sql, env=env)
    dsn = f"postgres://devkit_reader:{secret['reader']}@127.0.0.1:{PORT}/{DB}?sslmode=disable"
    config = '[[sources]]\nid = "napare_devkit_test"\ndsn = ' + json.dumps(dsn) + '\n\n[[tools]]\nname = "execute_sql"\nsource = "napare_devkit_test"\nreadonly = true\nmax_rows = 100\n\n[[tools]]\nname = "search_objects"\nsource = "napare_devkit_test"\n'
    (ROOT / '.cache/ai-devkit/dbhub.toml').write_text(config, encoding='utf8')
    print(f'Isolated synthetic PostgreSQL ready on loopback:{PORT}; SELECT-only DBHub role configured. Credentials remain ignored.')

if __name__ == '__main__':
    main()
